import { createFileRoute, Link } from "@tanstack/react-router";
import { useEffect, useRef, useState } from "react";
import {
  ArrowDown,
  ArrowLeft,
  ArrowUp,
  Check,
  ChevronDown,
  ExternalLink,
  Scale,
  Trash2,
  X,
} from "lucide-react";
import { toast } from "sonner";
import { deleteValuation, getHistory, importHistory, type Valuation } from "@/lib/history";
import { exportHistoryPdf, extractHistoryJsonFromPdf } from "@/lib/historyPdf";
import { translations, type Lang } from "@/lib/i18n";
import { formatEur, formatUsd } from "@/lib/formatPrice";
import { extractPricePerSqm } from "@/lib/pricePerSqm";
import { sourceLabel, sourceUrl } from "@/lib/sourceLinks";

const ITEMS_PAGE = 5;
const MAX_IMPORT_BYTES = 80 * 1024 * 1024; // 80 MB (fotos sin comprimir)

export const Route = createFileRoute("/history")({
  head: () => ({
    meta: [
      { title: "Lume — Historial de tasaciones" },
      {
        name: "description",
        content: "Consulta el historial de tasaciones realizadas con Lume.",
      },
    ],
  }),
  component: HistoryPage,
});

function HistoryPage() {
  const [items, setItems] = useState<Valuation[]>([]);
  const [openId, setOpenId] = useState<string | null>(null);
  const [lang, setLang] = useState<Lang>("es");
  const [activeTab, setActiveTab] = useState<string>("all");
  const [page, setPage] = useState(1);
  const [loading, setLoading] = useState(true);
  const [compareIds, setCompareIds] = useState<string[]>([]);
  const [compareMode, setCompareMode] = useState(false);
  const [showCompare, setShowCompare] = useState(false);
  const fileRef = useRef<HTMLInputElement | null>(null);

  const toggleCompare = (id: string) => {
    setCompareIds((prev) => {
      if (prev.includes(id)) return prev.filter((x) => x !== id);
      if (prev.length >= 3) {
        toast.error(t.compareMax);
        return prev;
      }
      return [...prev, id];
    });
  };

  const reloadHistory = async () => {
    const h = await getHistory();
    setItems(h);
    setLoading(false);
  };

  const handleExport = async () => {
    try {
      await exportHistoryPdf(lang);
      toast.success(t.exportOk);
    } catch {
      toast.error(t.exportError);
    }
  };

  const handleImport = async (file: File) => {
    try {
      // Paso 1: validar tamaño antes de leer el archivo
      if (file.size > MAX_IMPORT_BYTES) {
        throw new Error(
          lang === "es"
            ? "El archivo es demasiado grande (máx. 20 MB)"
            : "File too large (max 20 MB)",
        );
      }
      const isPdf = file.type === "application/pdf" || file.name.toLowerCase().endsWith(".pdf");
      const isJson =
        !isPdf && (file.type === "application/json" || file.name.toLowerCase().endsWith(".json"));
      if (!isPdf && !isJson) {
        throw new Error(
          lang === "es"
            ? "El archivo debe ser un PDF Premium generado por Lume"
            : "File must be a Premium PDF generated by Lume",
        );
      }
      const raw = await file.text();
      // Los PDF Premium de Lume llevan el historial incrustado tras %%EOF;
      // también aceptamos JSON por compatibilidad con copias antiguas.
      const json = isPdf ? extractHistoryJsonFromPdf(raw) : raw;
      const n = await importHistory(json);
      await reloadHistory();
      toast.success(t.importOk(n));
    } catch (e) {
      const msg =
        e instanceof Error && e.message === "PDF_NO_LUME_DATA"
          ? lang === "es"
            ? "Este PDF no contiene datos de Lume. Solo se pueden importar los PDF Premium exportados desde Lume."
            : "This PDF has no Lume data. Only Premium PDFs exported from Lume can be imported."
          : e instanceof Error
            ? e.message
            : t.importError;
      toast.error(msg);
    }
  };

  const handleDelete = async (id: string) => {
    try {
      await deleteValuation(id);
      setCompareIds((prev) => prev.filter((x) => x !== id));
      await reloadHistory();
    } catch {
      toast.error(lang === "es" ? "Error al eliminar" : "Error deleting item");
    }
  };

  useEffect(() => {
    const read = () => {
      void reloadHistory();
      setLang((localStorage.getItem("lume:lang") as Lang) || "es");
    };
    read();

    window.addEventListener("lume:history", read);
    window.addEventListener("lume:lang", read);
    return () => {
      window.removeEventListener("lume:history", read);
      window.removeEventListener("lume:lang", read);
    };
  }, []);

  useEffect(() => {
    setPage(1);
  }, [activeTab]);

  const t = translations[lang];
  const locale = lang === "es" ? "es-ES" : "en-US";
  const usedCategories = Array.from(
    new Set(items.map((v) => (v.category && v.category in t.categories ? v.category : "other"))),
  );
  const filtered =
    activeTab === "all" ? items : items.filter((v) => (v.category ?? "other") === activeTab);
  const totalPages = Math.max(1, Math.ceil(filtered.length / ITEMS_PAGE));

  // Ajuste automático de página si se eliminan elementos y la página actual queda fuera de rango
  useEffect(() => {
    if (page > totalPages) {
      setPage(totalPages);
    }
  }, [page, totalPages]);

  const paginatedItems = filtered.slice((page - 1) * ITEMS_PAGE, page * ITEMS_PAGE);
  const allLabel = lang === "es" ? "Todas" : "All";

  return (
    <div className="relative min-h-screen">
      <div className="pointer-events-none absolute inset-x-0 top-0 h-[400px] bg-[radial-gradient(ellipse_at_top,oklch(0.72_0.2_45/30%),transparent_70%)] blur-3xl" />
      <div className="relative mx-auto max-w-xl px-5 pb-16 pt-8">
        <header className="flex items-center gap-3">
          <Link
            to="/"
            className="glass-crystal flex h-10 w-10 items-center justify-center rounded-full text-primary"
            aria-label={t.back}
          >
            <ArrowLeft className="h-5 w-5" />
          </Link>
          <h1 className="flex-1 text-xl font-semibold text-gradient-gold">{t.history}</h1>
          <div className="flex flex-col items-center gap-0.5">
            <button
              type="button"
              onClick={() => void handleExport()}
              className="glass-crystal flex h-10 items-center gap-1.5 rounded-full px-3 text-xs font-semibold text-primary transition hover:bg-primary/15"
              aria-label={t.exportHistory}
            >
              <ArrowUp className="h-4 w-4" />
              <span className="hidden sm:inline">{t.exportHistory}</span>
            </button>
            <span className="text-[9px] font-semibold uppercase tracking-wider text-muted-foreground">
              PDF
            </span>
          </div>
          <div className="flex flex-col items-center gap-0.5">
            <button
              type="button"
              onClick={() => fileRef.current?.click()}
              className="glass-crystal flex h-10 items-center gap-1.5 rounded-full px-3 text-xs font-semibold text-primary transition hover:bg-primary/15"
              aria-label={t.importHistory}
            >
              <ArrowDown className="h-4 w-4" />
              <span className="hidden sm:inline">{t.importHistory}</span>
            </button>
            <span className="text-[9px] font-semibold uppercase tracking-wider text-muted-foreground">
              PDF
            </span>
          </div>
          <input
            ref={fileRef}
            type="file"
            accept="application/pdf,.pdf,application/json,.json"
            className="hidden"
            onChange={(e) => {
              const f = e.target.files?.[0];
              e.target.value = "";
              if (f) void handleImport(f);
            }}
          />
        </header>

        {items.length > 0 && (
          <div className="mt-5 flex min-h-[44px] flex-wrap content-start items-center gap-2 transition-all duration-300 ease-out">
            {[
              { key: "all", label: allLabel },
              ...usedCategories.map((k) => ({
                key: k,
                label: t.categories[k as keyof typeof t.categories] ?? k,
              })),
            ].map((tab) => (
              <button
                key={tab.key}
                onClick={() => setActiveTab(tab.key)}
                className={`shrink-0 rounded-full border px-3.5 py-2 text-xs leading-none whitespace-nowrap transition-all duration-200 sm:px-3 sm:py-1.5 ${
                  activeTab === tab.key
                    ? "border-primary/60 bg-primary/20 text-primary font-semibold"
                    : "border-primary/20 bg-background/40 text-muted-foreground hover:text-primary"
                }`}
              >
                {tab.label}
              </button>
            ))}
          </div>
        )}

        {items.length > 1 && (
          <div className="mt-3 flex items-center justify-between gap-2">
            {compareMode ? (
              <p className="text-[11px] text-muted-foreground">{t.compareHint}</p>
            ) : (
              <span />
            )}
            <div className="flex shrink-0 items-center gap-2">
              {compareMode && compareIds.length >= 2 && (
                <button
                  type="button"
                  onClick={() => setShowCompare(true)}
                  className="glass-crystal flex items-center gap-1.5 rounded-full px-3 py-1.5 text-xs font-semibold text-primary transition hover:bg-primary/15"
                >
                  <Scale className="h-3.5 w-3.5" />
                  {t.compareSelected(compareIds.length)}
                </button>
              )}
              <button
                type="button"
                onClick={() => {
                  setCompareMode((v) => !v);
                  setCompareIds([]);
                }}
                className={`flex items-center gap-1.5 rounded-full px-3 py-1.5 text-xs font-semibold transition ${
                  compareMode
                    ? "bg-primary/20 text-primary"
                    : "glass-crystal text-primary hover:bg-primary/15"
                }`}
              >
                {!compareMode && <Scale className="h-3.5 w-3.5" />}
                {compareMode ? t.cancel : t.compare}
              </button>
            </div>
          </div>
        )}

        {loading ? (
          <p className="mt-16 text-center text-sm text-muted-foreground animate-pulse">
            {lang === "es" ? "Cargando…" : "Loading…"}
          </p>
        ) : paginatedItems.length === 0 ? (
          <div className="glass-crystal mt-12 rounded-2xl p-8 text-center">
            <p className="text-sm text-muted-foreground">{t.empty}</p>
          </div>
        ) : (
          <>
            <ul className="mt-6 space-y-3">
              {paginatedItems.map((v) => {
                const isOpen = openId === v.id;
                return (
                  <li
                    key={v.id}
                    className="glass-crystal rounded-2xl p-4 transition-all duration-300 ease-out"
                  >
                    <button
                      type="button"
                      onClick={() => setOpenId(isOpen ? null : v.id)}
                      aria-expanded={isOpen}
                      className="flex w-full gap-3 text-left"
                    >
                      {compareMode && (
                        <span
                          role="checkbox"
                          aria-checked={compareIds.includes(v.id)}
                          tabIndex={0}
                          onClick={(e) => {
                            e.stopPropagation();
                            toggleCompare(v.id);
                          }}
                          onKeyDown={(e) => {
                            if (e.key === "Enter" || e.key === " ") {
                              e.stopPropagation();
                              e.preventDefault();
                              toggleCompare(v.id);
                            }
                          }}
                          aria-label={t.compare}
                          className={`mt-0.5 flex h-5 w-5 shrink-0 items-center justify-center rounded-full border transition ${
                            compareIds.includes(v.id)
                              ? "border-primary bg-primary text-primary-foreground"
                              : "border-primary/40 bg-background/40 text-transparent"
                          }`}
                        >
                          <Check className="h-3.5 w-3.5" />
                        </span>
                      )}
                      <img
                        src={v.thumbnail}
                        alt=""
                        className="h-16 w-16 shrink-0 rounded-lg object-cover ring-1 ring-primary/30"
                      />
                      <div className="min-w-0 flex-1">
                        <div className="grid grid-cols-[minmax(0,1fr)_auto] items-start gap-2">
                          <h2 className="min-w-0 truncate text-sm font-semibold text-foreground">
                            {v.title}
                          </h2>
                          <span
                            role="button"
                            tabIndex={0}
                            onClick={(e) => {
                              e.stopPropagation();
                              void handleDelete(v.id);
                            }}
                            onKeyDown={(e) => {
                              if (e.key === "Enter" || e.key === " ") {
                                e.stopPropagation();
                                void handleDelete(v.id);
                              }
                            }}
                            className="-m-1 shrink-0 p-1 text-muted-foreground transition hover:text-destructive"
                            aria-label={t.delete}
                          >
                            <Trash2 className="h-4 w-4" />
                          </span>
                        </div>
                        <p className="mt-0.5 text-[11px] text-muted-foreground">
                          {new Date(v.createdAt).toLocaleString(locale)}
                        </p>
                        <div className="mt-2 flex flex-wrap items-center gap-2 text-xs">
                          <span className="rounded-full border border-primary/30 bg-primary/15 px-2.5 py-1 font-semibold leading-tight text-primary">
                            {formatEur(v.priceEurMin)} – {formatEur(v.priceEurMax)}
                          </span>
                          <span className="rounded-full border border-accent/30 bg-accent/15 px-2.5 py-1 font-semibold leading-tight text-accent">
                            {formatUsd(v.priceUsdMin)} – {formatUsd(v.priceUsdMax)}
                          </span>
                          <ChevronDown
                            aria-hidden="true"
                            className={`ml-auto h-6 w-6 shrink-0 text-yellow-400 transition-transform duration-300 ${isOpen ? "rotate-180" : ""}`}
                          />
                        </div>
                        {!isOpen && (
                          <p className="mt-2 line-clamp-2 text-xs text-muted-foreground">
                            {v.identification}
                          </p>
                        )}
                      </div>
                    </button>

                    <div
                      className={`grid transition-all duration-300 ease-out ${
                        isOpen
                          ? "mt-4 grid-rows-[1fr] border-t border-primary/20 pt-3 opacity-100"
                          : "mt-0 grid-rows-[0fr] border-t-0 border-transparent pt-0 opacity-0"
                      }`}
                    >
                      <div className="overflow-hidden space-y-3">
                        <div>
                          <p className="text-[10px] uppercase tracking-wider text-muted-foreground">
                            {t.identification}
                          </p>
                          <p className="mt-1 text-sm leading-relaxed text-foreground/90">
                            {v.identification}
                          </p>
                        </div>
                        <p className="text-[11px] font-medium uppercase text-primary">
                          {t.confidence}:{" "}
                          {t.confidenceLevels[v.confidence as keyof typeof t.confidenceLevels] ??
                            v.confidence}
                        </p>
                        {v.notes && (
                          <div className="rounded-xl border border-primary/25 bg-primary/10 p-3 backdrop-blur-md">
                            <p className="text-[10px] font-bold uppercase tracking-wider text-primary">
                              {t.notes}
                            </p>
                            {extractPricePerSqm(v.notes).length > 0 && (
                              <div className="mt-2 flex flex-wrap gap-1.5">
                                {extractPricePerSqm(v.notes).map((p) => (
                                  <span
                                    key={p}
                                    className="rounded-full border border-primary/40 bg-primary/20 px-2.5 py-1 text-[11px] font-semibold tabular-nums leading-tight text-primary"
                                  >
                                    {p}
                                  </span>
                                ))}
                              </div>
                            )}
                            <p className="mt-1.5 text-xs leading-relaxed text-foreground/90">
                              {v.notes}
                            </p>
                          </div>
                        )}
                        {v.sources && v.sources.length > 0 && (
                          <div>
                            <p className="text-[10px] uppercase tracking-wider text-muted-foreground">
                              {t.sources}
                            </p>
                            <div className="mt-2 flex flex-wrap items-center gap-1.5">
                              {v.sources.map((s, i) => (
                                <a
                                  key={i}
                                  href={sourceUrl(s, v.title)}
                                  title={s}
                                  target="_blank"
                                  rel="noopener noreferrer"
                                  className="inline-flex items-center gap-1 rounded-full border border-primary/30 bg-primary/10 px-2.5 py-1.5 text-[11px] leading-tight text-primary transition hover:bg-primary/15"
                                >
                                  {sourceLabel(s)}
                                  <ExternalLink className="h-3 w-3 shrink-0" />
                                </a>
                              ))}
                            </div>
                          </div>
                        )}
                      </div>
                    </div>
                  </li>
                );
              })}
            </ul>

            {totalPages > 1 && (
              <nav
                aria-label={lang === "es" ? "Paginación del historial" : "History pagination"}
                className="mt-6 flex items-center justify-between gap-3"
              >
                <button
                  type="button"
                  onClick={() => setPage((p) => Math.max(1, p - 1))}
                  disabled={page <= 1}
                  className="glass-crystal rounded-full px-4 py-2 text-xs font-semibold text-primary transition hover:bg-primary/15 disabled:opacity-40 disabled:hover:bg-transparent"
                >
                  {t.previous}
                </button>
                <span className="text-xs text-muted-foreground">
                  {t.page} {page} {t.of} {totalPages}
                </span>
                <button
                  type="button"
                  onClick={() => setPage((p) => Math.min(totalPages, p + 1))}
                  disabled={page >= totalPages}
                  className="glass-crystal rounded-full px-4 py-2 text-xs font-semibold text-primary transition hover:bg-primary/15 disabled:opacity-40 disabled:hover:bg-transparent"
                >
                  {t.next}
                </button>
              </nav>
            )}
          </>
        )}
      </div>

      {showCompare && (
        <div className="fixed inset-0 z-50 flex flex-col bg-background/95 backdrop-blur-xl">
          <header className="flex items-center gap-3 border-b border-primary/20 px-5 py-4">
            <h2 className="flex-1 text-lg font-semibold text-gradient-gold">{t.compareTitle}</h2>
            <button
              type="button"
              onClick={() => setShowCompare(false)}
              className="glass-crystal flex h-9 w-9 items-center justify-center rounded-full text-primary"
              aria-label={t.back}
            >
              <X className="h-4 w-4" />
            </button>
          </header>
          <div className="flex-1 overflow-x-auto overflow-y-auto px-5 py-5">
            {compareIds.length < 2 ? (
              <p className="mt-10 text-center text-sm text-muted-foreground">{t.compareEmpty}</p>
            ) : (
              <div className="flex min-h-full gap-4">
                {compareIds
                  .map((id) => items.find((v) => v.id === id))
                  .filter((v): v is Valuation => Boolean(v))
                  .map((v) => (
                    <div
                      key={v.id}
                      className="glass-crystal flex w-64 shrink-0 flex-col gap-3 rounded-2xl p-4"
                    >
                      <img
                        src={v.thumbnail}
                        alt=""
                        className="h-32 w-full rounded-lg object-cover ring-1 ring-primary/30"
                      />
                      <h3 className="text-sm font-semibold leading-snug text-foreground">
                        {v.title}
                      </h3>
                      <p className="text-[11px] text-muted-foreground">
                        {new Date(v.createdAt).toLocaleString(locale)}
                      </p>
                      <div>
                        <p className="text-[10px] uppercase tracking-wider text-muted-foreground">
                          {t.category}
                        </p>
                        <p className="mt-0.5 text-xs font-medium text-foreground">
                          {v.category && v.category in t.categories
                            ? t.categories[v.category as keyof typeof t.categories]
                            : t.categories.other}
                        </p>
                      </div>
                      <div className="flex flex-col gap-1.5">
                        <span className="rounded-full border border-primary/30 bg-primary/15 px-2.5 py-1 text-center text-xs font-semibold leading-tight text-primary">
                          {formatEur(v.priceEurMin)} – {formatEur(v.priceEurMax)}
                        </span>
                        <span className="rounded-full border border-accent/30 bg-accent/15 px-2.5 py-1 text-center text-xs font-semibold leading-tight text-accent">
                          {formatUsd(v.priceUsdMin)} – {formatUsd(v.priceUsdMax)}
                        </span>
                      </div>
                      <div>
                        <p className="text-[10px] uppercase tracking-wider text-muted-foreground">
                          {t.confidence}
                        </p>
                        <p className="mt-0.5 text-xs font-medium text-primary">
                          {t.confidenceLevels[v.confidence as keyof typeof t.confidenceLevels] ??
                            v.confidence}
                        </p>
                      </div>
                      {v.notes && (
                        <div>
                          <p className="text-[10px] uppercase tracking-wider text-muted-foreground">
                            {t.notes}
                          </p>
                          <p className="mt-0.5 line-clamp-4 text-xs leading-relaxed text-foreground/90">
                            {v.notes}
                          </p>
                        </div>
                      )}
                    </div>
                  ))}
              </div>
            )}
          </div>
        </div>
      )}
    </div>
  );
}
